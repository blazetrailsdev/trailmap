/**
 * THE MARKDOWN GATE. `app/helpers/markdown-helper.ts` is a line-for-line port
 * of ringo's `webhook/markdown.go`, and it was verified exactly once — by hand,
 * in a scratch directory, at merge. Nothing held the two together afterwards,
 * so the next edit to either side would have drifted in silence and the
 * acceptance criterion behind the port ("a reader moving between the two
 * dashboards sees the same document") would have quietly stopped being true.
 *
 * So: render EVERY RFC and story body in the tasks checkout through both
 * implementations and diff. The Go side is ringo's own function, vendored
 * verbatim at a pinned commit (vendor/ringo/go/markdown.go, regenerated by
 * scripts/vendor-ringo.sh) because btwhooks has no remote for CI to check out.
 * A re-description of the renderer would only prove that two readings of the Go
 * agree; running the Go proves the renderers do.
 *
 * The ONE tolerated difference is the double-quote entity: Go's
 * `html.EscapeString` writes `&#34;` where trails' `htmlEscape` writes
 * `&quot;`. Same character, so it is normalized here rather than forced on
 * either side.
 *
 *     TASKS_DIR=<tasks checkout> pnpm gate:markdown [--self-test]
 */
import { getChildProcessAsync } from "@blazetrails/activesupport/child-process-adapter";
import { getFsAsync, getPathAsync } from "@blazetrails/activesupport";
import { argv, cwd, env, exit } from "@blazetrails/activesupport/process-adapter";
import { verifyRingoPin } from "./ringo-pin.js";
import { renderMarkdown } from "../app/helpers/markdown-helper.js";
import { stripFrontmatter } from "../app/models/concerns/document.js";

/** How many differing documents to name before the report stops being useful. */
const REPORT_LIMIT = 5;

async function main(argv: readonly string[]): Promise<number> {
  const fs = await getFsAsync();
  const path = await getPathAsync();
  const child = await getChildProcessAsync();

  // The gate mutates its OWN copy of the trailmap output, never the helper: a
  // self-test that edited the file it is testing would leave the repo dirty
  // when it failed, which is when it matters most.
  const selfTest = argv.includes("--self-test");

  // The snapshot is the reference implementation; prove it is the one
  // scripts/vendor-ringo.sh took before diffing anything against it.
  try {
    console.log(`ringo pin: ${await verifyRingoPin()}`);
  } catch (e) {
    console.error(`error: ${(e as Error).message}`);
    return 1;
  }

  const tasksDir = env.TASKS_DIR ?? env.TASKS_CLI ?? path.join(cwd(), "tasks");
  const rfcsDir = path.join(tasksDir, "rfcs");
  if (!(await fs.exists(rfcsDir))) {
    console.error(`error: no RFC tree at ${rfcsDir} — set TASKS_DIR to the tasks checkout`);
    return 1;
  }

  const files = (await markdownFilesIn(fs, path, rfcsDir)).sort();
  if (files.length === 0) {
    console.error(`error: no markdown under ${rfcsDir} — an empty corpus proves nothing`);
    return 1;
  }

  const corpus: Record<string, string> = {};
  for (const file of files) {
    corpus[path.relative!(tasksDir, file)] = stripFrontmatter(await fs.readFile!(file, "utf8"));
  }

  // stdout goes to a FILE, not a buffer: the whole corpus rendered is megabytes
  // of HTML, and spawnSync's default 1MB buffer truncates it mid-JSON.
  const captured = path.join(cwd(), "tmp", "ringo-markdown.json");
  await fs.mkdir!(path.dirname(captured), { recursive: true });
  const result = child.spawnSync("go", ["run", ".", "markdown"], {
    cwd: path.join(cwd(), "vendor", "ringo", "go"),
    encoding: "utf8",
    input: JSON.stringify(corpus),
    out: captured,
  });
  if (result.status !== 0) {
    console.error(`error: ringo's renderer exited ${result.status}: ${result.stderr.trim()}`);
    return 1;
  }
  const ringo = JSON.parse(await fs.readFile!(captured, "utf8")) as Record<string, string>;

  const problems: string[] = [];
  for (const name of Object.keys(corpus)) {
    // `&#34;` is Go's spelling of `&quot;`. Same character, documented
    // difference, normalized rather than diffed.
    const theirs = (ringo[name] ?? "").replaceAll("&#34;", "&quot;");
    let ours = String(renderMarkdown(corpus[name]!));
    if (selfTest && problems.length === 0) ours = ours.replace("<p>", "<P>");
    if (theirs !== ours) problems.push(`${name}: ${firstDifference(theirs, ours)}`);
  }

  if (selfTest) {
    if (problems.length === 1) {
      console.log(`SELF-TEST OK: a one-character change turned the gate red (${problems[0]})`);
      return 0;
    }
    console.error(
      `SELF-TEST FAILED: a one-character change produced ${problems.length} differences, want 1`,
    );
    return 1;
  }
  if (problems.length === 0) {
    console.log(`EQUIVALENT: ${files.length} documents render identically to ringo's.`);
    return 0;
  }
  console.error(`NOT EQUIVALENT — ${problems.length} of ${files.length} documents differ:`);
  for (const p of problems.slice(0, REPORT_LIMIT)) console.error(`  ${p}`);
  if (problems.length > REPORT_LIMIT) console.error(`  ... and ${problems.length - REPORT_LIMIT} more`);
  return 1;
}

/**
 * Every `.md` under `dir`. The async filesystem adapter models no `stat`, so a
 * directory is whatever `readdir` accepts — the failure is the answer.
 */
async function markdownFilesIn(
  fs: Awaited<ReturnType<typeof getFsAsync>>,
  path: Awaited<ReturnType<typeof getPathAsync>>,
  dir: string,
): Promise<string[]> {
  const out: string[] = [];
  for (const name of await fs.readdir!(dir)) {
    const full = path.join(dir, name);
    if (name.endsWith(".md")) {
      out.push(full);
      continue;
    }
    try {
      await fs.readdir!(full);
    } catch {
      continue; // a file that is not markdown, which is nothing to render
    }
    out.push(...(await markdownFilesIn(fs, path, full)));
  }
  return out;
}

/** Where the two renderings part, which is the only useful thing to report. */
function firstDifference(theirs: string, ours: string): string {
  let at = 0;
  while (at < theirs.length && at < ours.length && theirs[at] === ours[at]) at++;
  const window = (s: string) => JSON.stringify(s.slice(Math.max(0, at - 20), at + 40));
  return `differs at byte ${at}\n    ringo:    ${window(theirs)}\n    trailmap: ${window(ours)}`;
}

exit(await main(argv));
