#!/usr/bin/env bash
#
# Regenerate vendor/ringo/ — the pinned copy of ringo's own code that the two
# ringo gates run against, and that trailmap runs for the renderers it shares
# with ringo instead of porting.
#
# ringo (deanmarano/btwhooks) has no GitHub remote, so CI cannot check it out
# and a gate that needs it would only ever run on one laptop. The answer is the
# one this repo already uses for the framework: vendor a pinned snapshot, and
# make regenerating it a script rather than a copy-paste. What is vendored is
# ringo's CODE, verbatim — not a re-description of it — so the gates execute
# ringo's own list logic and ringo's own renderer, and a divergence is a real
# divergence rather than a disagreement between two readings of the Go.
#
#     ./scripts/vendor-ringo.sh ~/github/deanmarano/btwebooks [ref]
#
# Bumping the pin is its own PR, for the reason README gives about the trails
# tarballs: a gate that goes red must be revertible without taking application
# work with it.
set -euo pipefail

src=${1:-}
ref=${2:-HEAD}
if [ -z "$src" ] || [ ! -d "$src/webhook" ]; then
  echo "usage: $0 <btwhooks-checkout> [ref]" >&2
  exit 2
fi
out=$(cd "$(dirname "$0")/.." && pwd)/vendor/ringo
mkdir -p "$out/go"

commit=$(git -C "$src" rev-parse "$ref")
show() { git -C "$src" show "$commit:$1"; }

# The browser scripts, verbatim between the FIRST <script> and its </script>. The tab
# predicates, the sort comparators and the tab counts of both list pages live
# there — ringo assembles those pages in the browser — so this IS the thing
# /rfcs and /backlog were ported from.
#
# The one rewrite: two `const ICON_* = ` lines are Go string concatenation
# spliced into the JS (`+ "`" + iconIssueOpened + "`" +`), which is not JS and
# never reaches a browser in that form. They carry an SVG the gate never looks
# at, so they become a placeholder literal.
extractScript() {
  show "$1" |
    awk '/^<script>$/ && !seen { on = 1; seen = 1; next } /^<\/script>$/ { on = 0 } on' |
    sed -E "s|^const (ICON_[A-Z_]+) = .*$|const \1 = '<svg/>'; // vendored: Go-spliced SVG|"
}

header() { printf '// GENERATED by scripts/vendor-ringo.sh from btwhooks %s\n// source: %s\n// DO NOT EDIT.\n' "$commit" "$1"; }

{ header "webhook/rfcs.go <script> (the /rfcs page)"; extractScript webhook/rfcs.go; } > "$out/rfcs-draw.js"
{ header "webhook/backlog.go <script> (the /backlog page)"; extractScript webhook/backlog.go; } > "$out/backlog-draw.js"

# The Go half: ringo's `core` package and the command that wraps it, whole.
# core is the part of ringo that is pure computation — the markdown renderer,
# the pane terminal replay, the RFC story tally — and ringo keeps it
# standard-library only precisely so it can be lifted out like this (its own
# stdlib_test.go holds that rule). It lands under go/ at the paths it has in
# btwhooks, beside a go.mod naming btwhooks' module, so cmd/core's import of
# ".../btwhooks/core" resolves inside this directory and nothing is rewritten:
#
#     cd vendor/ringo/go && go run ./cmd/core markdown-corpus|counts|pane|markdown
#
# Tests stay behind. They are ringo's to run; what is vendored is what executes.
rm -rf "$out/go"
mkdir -p "$out/go"
goFiles=$(git -C "$src" ls-tree -r --name-only "$commit" -- core cmd/core | grep '\.go$' | grep -v '_test\.go$')
[ -n "$goFiles" ] || { echo "no core/ or cmd/core at $commit — is this pin older than ringo's core package?" >&2; exit 1; }
for f in $goFiles; do
  mkdir -p "$out/go/$(dirname "$f")"
  { header "$f"; show "$f"; } > "$out/go/$f"
done
{
  header "go.mod (module and go lines only: core has no dependencies to carry)"
  show go.mod | grep -E '^(module|go) '
} > "$out/go/go.mod"

# The toolchain that built core.wasm below. CI's setup-go reads this file, so
# the gates and the reproducibility check run the same Go that produced the
# committed binary — a different release emits different bytes.
go env GOVERSION | sed 's/^go//' > "$out/go/.go-version"

# core.wasm: the vendored source above, compiled for WASI. This is what
# trailmap EXECUTES at runtime, so it is committed — the image needs no Go
# toolchain — and it is reproducible, so CI can prove the binary is this source
# and not something else (scripts/build-ringo-wasm.sh, which both sides run).
"$(dirname "$0")/build-ringo-wasm.sh" "$out/core.wasm"

# Every ringo file that touches SQL — opens a handle, executes a statement, or
# spells a write — whole, for the write-protocol test
# (test/config/write-protocol.test.ts) to check its DSNs and its SQL writes. A
# file executing against a *sql.DB opened elsewhere still names `.Exec` or the
# statement, so it is caught too. Kept out of go/ so `go run` over the command
# never compiles them. The set is discovered across the whole repository, not
# listed, so a new SQL site is vendored the next time the pin moves.
mkdir -p "$out/db"
sqlPattern='sql\.Open|\.(Exec|Prepare)(Context)?\(|insert (or [a-z]+ )?into|replace into|delete from|update +[a-z_"`]+ +set'
dbFiles=$(git -C "$src" grep -liE "$sqlPattern" "$commit" -- '*.go' ':!*_test.go' | sed "s/^$commit://")
[ -n "$dbFiles" ] || { echo "no SQL site in ringo — the write-protocol test would scan nothing" >&2; exit 1; }
rm -f "$out"/db/*.go
for f in $dbFiles; do { header "$f"; show "$f"; } > "$out/db/$(basename "$f")"; done

printf '%s\n' "$commit" > "$out/PIN"
(cd "$out" && { echo rfcs-draw.js; echo backlog-draw.js; echo core.wasm; find go db -type f | LC_ALL=C sort; } | xargs sha256sum) > "$out/SHA256"
echo "vendored ringo $commit -> $out"
