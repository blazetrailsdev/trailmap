#!/usr/bin/env bash
#
# Regenerate vendor/ringo/ — the pinned copy of ringo's own code that the two
# ringo gates run against, and that trailmap runs for the renderers it shares
# with ringo instead of porting.
#
# What lands here: the two list pages' browser scripts, the /graphs/parity
# page's stylesheet and chart engine, ringo's `core` package and the WASM built
# from it, and every ringo file that touches SQL. The parity page's card markup
# is the one output that lands OUTSIDE this directory — it is a view partial,
# at app/views/parity-graphs/_cards.html.tse.
#
# ringo (deanmarano/btwhooks) has no GitHub remote, so CI cannot check it out
# and a gate that needs it would only ever run on one laptop. The answer is the
# one this repo already uses for the framework: vendor a pinned snapshot, and
# make regenerating it a script rather than a copy-paste. What is vendored is
# ringo's CODE, verbatim — not a re-description of it — so the gates execute
# ringo's own list logic and ringo's own renderer, and a divergence is a real
# divergence rather than a disagreement between two readings of the Go.
#
#     ./scripts/vendor-ringo.sh ~/github/deanmarano/btwebooks [ref]
#
# Bumping the pin is its own PR, for the reason README gives about the trails
# tarballs: a gate that goes red must be revertible without taking application
# work with it.
set -euo pipefail

src=${1:-}
ref=${2:-HEAD}
if [ -z "$src" ] || [ ! -d "$src/webhook" ]; then
  echo "usage: $0 <btwhooks-checkout> [ref]" >&2
  exit 2
fi
out=$(cd "$(dirname "$0")/.." && pwd)/vendor/ringo
mkdir -p "$out/go"

commit=$(git -C "$src" rev-parse "$ref")
show() { git -C "$src" show "$commit:$1"; }

# The browser scripts, verbatim between the FIRST <script> and its </script>. The tab
# predicates, the sort comparators and the tab counts of both list pages live
# there — ringo assembles those pages in the browser — so this IS the thing
# /rfcs and /backlog were ported from.
#
# The one rewrite: two `const ICON_* = ` lines are Go string concatenation
# spliced into the JS (`+ "`" + iconIssueOpened + "`" +`), which is not JS and
# never reaches a browser in that form. They carry an SVG the gate never looks
# at, so they become a placeholder literal.
extractScript() {
  show "$1" |
    awk '/^<script>$/ && !seen { on = 1; seen = 1; next } /^<\/script>$/ { on = 0 } on' |
    sed -E "s|^const (ICON_[A-Z_]+) = .*$|const \1 = '<svg/>'; // vendored: Go-spliced SVG|"
}

header() { printf '// GENERATED by scripts/vendor-ringo.sh from btwhooks %s\n// source: %s\n// DO NOT EDIT.\n' "$commit" "$1"; }

{ header "webhook/rfcs.go <script> (the /rfcs page)"; extractScript webhook/rfcs.go; } > "$out/rfcs-draw.js"
{ header "webhook/backlog.go <script> (the /backlog page)"; extractScript webhook/backlog.go; } > "$out/backlog-draw.js"

# The Go half: ringo's `core` package and the command that wraps it, whole.
# core is the part of ringo that is pure computation — the markdown renderer,
# the pane terminal replay, the RFC story tally — and ringo keeps it
# standard-library only precisely so it can be lifted out like this (its own
# stdlib_test.go holds that rule). It lands under go/ at the paths it has in
# btwhooks, beside a go.mod naming btwhooks' module, so cmd/core's import of
# ".../btwhooks/core" resolves inside this directory and nothing is rewritten:
#
#     cd vendor/ringo/go && go run ./cmd/core markdown-corpus|counts|pane|markdown
#
# Tests stay behind. They are ringo's to run; what is vendored is what executes.
rm -rf "$out/go"
mkdir -p "$out/go"
goFiles=$(git -C "$src" ls-tree -r --name-only "$commit" -- core cmd/core | grep '\.go$' | grep -v '_test\.go$')
[ -n "$goFiles" ] || { echo "no core/ or cmd/core at $commit — is this pin older than ringo's core package?" >&2; exit 1; }
for f in $goFiles; do
  mkdir -p "$out/go/$(dirname "$f")"
  { header "$f"; show "$f"; } > "$out/go/$f"
done
{
  header "go.mod (module and go lines only: core has no dependencies to carry)"
  show go.mod | grep -E '^(module|go) '
} > "$out/go/go.mod"

# The toolchain that built core.wasm below. CI's setup-go reads this file, so
# the gates and the reproducibility check run the same Go that produced the
# committed binary — a different release emits different bytes.
go env GOVERSION | sed 's/^go//' > "$out/go/.go-version"

# core.wasm: the vendored source above, compiled for WASI. This is what
# trailmap EXECUTES at runtime, so it is committed — the image needs no Go
# toolchain — and it is reproducible, so CI can prove the binary is this source
# and not something else (scripts/build-ringo-wasm.sh, which both sides run).
"$(dirname "$0")/build-ringo-wasm.sh" "$out/core.wasm"

# Every ringo file that touches SQL — opens a handle, executes a statement, or
# spells a write — whole, for the write-protocol test
# (test/config/write-protocol.test.ts) to check its DSNs and its SQL writes. A
# file executing against a *sql.DB opened elsewhere still names `.Exec` or the
# statement, so it is caught too. Kept out of go/ so `go run` over the command
# never compiles them. The set is discovered across the whole repository, not
# listed, so a new SQL site is vendored the next time the pin moves.
mkdir -p "$out/db"
sqlPattern='sql\.Open|\.(Exec|Prepare)(Context)?\(|insert (or [a-z]+ )?into|replace into|delete from|update +[a-z_"`]+ +set'
dbFiles=$(git -C "$src" grep -liE "$sqlPattern" "$commit" -- '*.go' ':!*_test.go' | sed "s/^$commit://")
[ -n "$dbFiles" ] || { echo "no SQL site in ringo — the write-protocol test would scan nothing" >&2; exit 1; }
rm -f "$out"/db/*.go
for f in $dbFiles; do { header "$f"; show "$f"; } > "$out/db/$(basename "$f")"; done

# The /graphs/parity page, as RINGO ASSEMBLES IT. The parity page's CSS and JS
# are not one raw string the way the two list pages' scripts are: `<style>` is
# four Go constants concatenated (graphPaletteCSS + graphChromeCSS + chartCSS +
# graphNavCSS) and `chartJS` is spliced into the middle of `<script>`, all of
# them in chart.go. An awk that cut between the tags would vendor the Go
# concatenation expression rather than the stylesheet.
#
# So this does not cut the source at all — it CALLS `HandleParityPage`, which
# takes no database and prints that assembly, and splits the page it returns.
# What lands in vendor/ringo is the chart engine ringo serves, byte for byte,
# which is the whole point of vendoring rather than porting: trailmap draws
# this page with ringo's own renderer, so a divergence in the picture is a
# divergence and not two readings of chart.go disagreeing.
#
# It needs a real tree to compile, not `git show`, and it must be the tree at
# $commit rather than whatever the checkout happens to have dirty — the lesson
# scripts/vendor-trails.sh records about labelling a pin with unpinned bytes.
# Hence a throwaway worktree, removed on the way out.
#
# The one rewrite, for the same reason the ICON_* lines above get one: line
# 1069 hard-codes ringo's own JSON path, and trailmap serves that data from its
# own route. Nothing else is touched.
parityWork=$(mktemp -d)
cleanupParity() {
  git -C "$src" worktree remove --force "$parityWork/pin" 2>/dev/null || true
  rm -rf "$parityWork"
}
trap cleanupParity EXIT
git -C "$src" worktree add --detach "$parityWork/pin" "$commit" >/dev/null
mkdir -p "$parityWork/pin/_vendor_extract"
cat > "$parityWork/pin/_vendor_extract/main.go" <<'EXTRACT'
// Prints ringo's assembled /graphs/parity document by calling ringo's own
// handler, so the Go-spliced CSS and JS constants are resolved by ringo.
package main

import (
	"fmt"
	"net/http"
	"net/http/httptest"
	"os"

	"github.com/deanmarano/btwhooks/webhook"
)

func main() {
	rec := httptest.NewRecorder()
	(&webhook.Parity{}).HandleParityPage(rec, httptest.NewRequest(http.MethodGet, "/graphs/parity", nil))
	if rec.Code != http.StatusOK {
		fmt.Fprintf(os.Stderr, "HandleParityPage returned %d\n", rec.Code)
		os.Exit(1)
	}
	os.Stdout.WriteString(rec.Body.String())
}
EXTRACT
page="$parityWork/page.html"
(cd "$parityWork/pin" && go run ./_vendor_extract) > "$page"
[ -s "$page" ] || { echo "ringo's parity page came back empty" >&2; exit 1; }

# Each piece is delimited by its own tag, so the splits do not depend on line
# numbers. The nav is deliberately NOT vendored: trailmap's layout supplies its
# own, as it does for every other page.
between() { awk -v from="$1" -v to="$2" '$0 == to { on = 0 } on; $0 == from { on = 1 }' "$page"; }

# A `//` header is not a CSS comment: a parser treats it as a bad selector and
# recovers by discarding everything through the next `{...}`, which would eat
# the `:root` palette the whole page draws its colors from.
{ printf '/* GENERATED by scripts/vendor-ringo.sh from btwhooks %s\n   source: webhook/parity_page.go + chart.go <style> (assembled by HandleParityPage)\n   DO NOT EDIT. */\n' "$commit"
  between '<style>' '</style>'; } > "$out/parity.css"

# The cards the script draws into, from the end of ringo's subnav to the
# script. This one lands as a VIEW PARTIAL rather than under vendor/ringo: it is
# markup a .tse template renders, views are compiled from app/views by
# trails-tsc-views, and a second committed copy would only be a thing to go
# stale. It is plain HTML with no template tags, which is a valid template.
cards=$(cd "$(dirname "$0")/.." && pwd)/app/views/parity-graphs
mkdir -p "$cards"
{ printf '<!-- GENERATED by scripts/vendor-ringo.sh from btwhooks %s\n     source: webhook/parity_page.go body (assembled by HandleParityPage)\n     DO NOT EDIT. -->\n' "$commit"
  awk '/^<div id="err"/ { on = 1 } /^<script>$/ { on = 0 } on' "$page"; } > "$cards/_cards.html.tse"

{ header "webhook/parity_page.go + chart.go <script> (assembled by HandleParityPage)"
  between '<script>' '</script>' |
    sed -E "s|'/spawnloop/parity\?metrics='|'/graphs/parity/data?metrics='|"; } > "$out/parity-draw.js"

for f in parity.css parity-draw.js; do
  [ -s "$out/$f" ] || { echo "extracted $f is empty — did ringo's parity page change shape?" >&2; exit 1; }
done
[ -s "$cards/_cards.html.tse" ] ||
  { echo "extracted _cards.html.tse is empty — did ringo's parity page change shape?" >&2; exit 1; }
grep -q '<%' "$cards/_cards.html.tse" &&
  { echo "ringo's parity body now contains a <% sequence, which .tse would compile" >&2; exit 1; }
grep -q '/graphs/parity/data' "$out/parity-draw.js" ||
  { echo "the /spawnloop/parity rewrite matched nothing — check webhook/parity_page.go's fetch URL" >&2; exit 1; }
grep -q '/spawnloop/' "$out/parity-draw.js" &&
  { echo "parity-draw.js still points at a /spawnloop path" >&2; exit 1; }
cleanupParity
trap - EXIT

# The module files ringo's parity handler compiles against, whole. The parity
# gate (scripts/ringo-parity-answers.sh) builds db/parity.go — the handler, as
# vendored above — into a throwaway module, and it needs ringo's own pin of
# modernc.org/sqlite to be the SQLite that answers. Unlike go/go.mod these
# carry the requires, and no header: go.sum has no comment syntax.
mkdir -p "$out/parity"
show go.mod > "$out/parity/go.mod"
show go.sum > "$out/parity/go.sum"

# The names parity.go takes from the rest of ringo's webhook package, which is
# not vendored — GENERATED here rather than hand-written under scripts/, so the
# gate runs ringo's code and not a copy someone has to keep in step.
#
# What parity.go needs is asked of the compiler, not read off a list: built
# alone, every package-level name it uses and does not define is an
# `undefined:` error. Each one must be in `borrowed` (extracted verbatim from
# wherever ringo defines it) or `placeholder` (stubbed, with the reason in the
# file); anything else fails this run by name, at the pin bump that introduced
# it, instead of as a Go error in CI later.
borrowed="envOr"
placeholder="parityHTML"
shimWork=$(mktemp -d)
trap 'rm -rf "$shimWork"' EXIT
mkdir -p "$shimWork/webhook"
cp "$out/parity/go.mod" "$out/parity/go.sum" "$shimWork/"
show webhook/parity.go > "$shimWork/webhook/parity.go"
undefined=$(cd "$shimWork" && go build -mod=mod -gcflags=-e ./webhook 2>&1 |
  grep -oE 'undefined: [A-Za-z_][A-Za-z0-9_]*' | sed 's/^undefined: //' | LC_ALL=C sort -u || true)
for name in $undefined; do
  case " $borrowed $placeholder " in
    *" $name "*) ;;
    *) echo "webhook/parity.go uses $name, which is defined elsewhere in ringo's webhook package and neither extracted nor stubbed — add it to vendor-ringo.sh's borrowed or placeholder list" >&2; exit 1 ;;
  esac
done
shim="$out/parity/shim.go"
# The bodies first, then the imports they use: each import of a defining file
# whose package name the extracted bodies spell as `name.`. ringo's envOr
# reached for strings.TrimSpace once already; a fixed import line would have
# turned that into a compile error rather than following it.
bodies="" imports=""
for name in $borrowed; do
  def=$(git -C "$src" grep -l "^func $name(" "$commit" -- 'webhook/*.go' ':!*_test.go' | sed -n "1s/^$commit://p")
  [ -n "$def" ] || { echo "no func $name in ringo's webhook package at $commit" >&2; exit 1; }
  file=$(show "$def")
  # No early `exit` in these readers: under pipefail a writer cut off by
  # one dies of SIGPIPE, and `set -e` ends the run with no message.
  body=$(awk -v start="^func $name[(]" '$0 ~ start && !done { on = 1 } on { print } on && /^}$/ { on = 0; done = 1 }' <<<"$file")
  bodies+=$'\n'"// $def"$'\n'"$body"$'\n'
  imports+=$(awk '/^import \(/ { on = 1; next } on && /^\)/ { on = 0 } on' <<<"$file" | grep -oE '"[^"]+"')$'\n'
done
used=""
for path in $(printf '%s\n' "$imports" | LC_ALL=C sort -u); do
  pkg=${path//\"/}; pkg=${pkg##*/}
  if grep -q "\b$pkg\." <<<"$bodies"; then used+="	$path"$'\n'; fi
done
{
  header "the names webhook/parity.go takes from the rest of package webhook"
  echo '//'
  echo '// Each function below is ringo'"'"'s own, extracted verbatim. parityHTML is a'
  echo '// PLACEHOLDER: it is the page HandleParityPage prints, which the parity gate'
  echo '// never calls, and the real one is a Go string that cannot be carried whole.'
  echo 'package webhook'
  echo
  if [ -n "$used" ]; then printf 'import (\n%s)\n' "$used"; fi
  printf '%s' "$bodies"
  echo
  echo 'const parityHTML = ""'
} > "$shim"
cp "$shim" "$shimWork/webhook/"
(cd "$shimWork" && go build -mod=mod ./webhook) ||
  { echo "webhook/parity.go does not compile against the generated $shim" >&2; exit 1; }
rm -rf "$shimWork"
trap - EXIT

printf '%s\n' "$commit" > "$out/PIN"
(cd "$out" && { echo rfcs-draw.js; echo backlog-draw.js; echo parity.css; echo parity-draw.js; echo core.wasm; find go db parity -type f | LC_ALL=C sort; } | xargs sha256sum) > "$out/SHA256"
echo "vendored ringo $commit -> $out"
