/**
 * THE LIST GATE. `/rfcs` and `/backlog` (#15) were ported from ringo's two
 * `draw()` scripts, and until this existed the only thing holding the port
 * still was unit tests written from the same reading of the Go that produced
 * the code — two readings by one author, agreeing. Two reviews of #15 said as
 * much from the other side: with no ringo checkout in the review environment,
 * the `webhook/*.go:LINE` citations could not be checked at all.
 *
 * So this runs RINGO'S OWN SCRIPTS. ringo assembles both list pages in the
 * browser out of one fetched dataset, so the tab predicates, the sort
 * comparators and the tab counts are JavaScript — vendored verbatim at a
 * pinned commit (vendor/ringo/*-draw.js, regenerated by
 * scripts/vendor-ringo.sh, because btwhooks has no remote CI could clone) and
 * executed here against a DOM stub. What comes back is the page ringo would
 * have painted; what it is compared against is the page trailmap renders, over
 * the same database, for every tab.
 *
 * Compared: MEMBERSHIP, ORDER, the TAB COUNTS and WHAT EACH ROW SAYS — the
 * queue position, the effective priority and whether it was inherited, the
 * effective packages and theirs, est-loc, the icebox tag, the cluster, the PR
 * and the assignee, and on the RFC side the priority, the done/total and the
 * clusters. The inherited-priority and inherited-packages rules are the ones
 * worth the extra comparison: they are own-then-parent fallbacks, they are
 * what the ready queue ranks by, and #15 ported them from the very script this
 * gate executes.
 *
 * Not the MARKUP, on either count — #7 gave trailmap its own status
 * vocabulary and its tabs are links rather than client-side repaints, and
 * neither is a defect. The two vocabularies are deliberate, so what is
 * compared is the VALUES a row states, pulled out of each side's own markup by
 * `scripts/page-extract.ts` exactly as the show-page gate does.
 *
 * TWO row values are NOT compared, and both are stated rather than left to be
 * noticed:
 *
 *   the status BADGE   Skipped on both sides. On `/backlog` that costs nothing
 *                      — trailmap shows the effective status and ringo's
 *                      dataset carries it too, and the tab predicates
 *                      partition on it, so a disagreement moves the row to
 *                      another tab and this gate goes red on membership.
 *                      `scripts/page-extract.ts` has the full argument.
 *   the `/rfcs` BAR    Not painted on ringo's side at all: `ringoRfcs` below
 *                      builds ringo's rows from the RFC columns and the
 *                      vendored `core.StoryCounts` and passes no `story_status`,
 *                      which is the map ringo's own server computes and its
 *                      script draws from. So trailmap's bar — effective-status
 *                      since the one-status rule, `storyStatusCounts` — is
 *                      UNCOMPARED here rather than proven equal to ringo's.
 *                      Making it comparable needs ringo's `story_status`,
 *                      which means the live-ringo gate (`pnpm gate:pages`),
 *                      not this one. See `RfcListRow`.
 *
 * Where the ringo side's DATA comes from matters as much as the logic: the
 * story rows and the ready queue are the tasks CLI's (`list`/`ready --json`,
 * the read model ringo ports), the RFC rows are plain columns read straight
 * out of the same snapshot, and the done/total on each RFC row is ringo's own
 * `core.StoryCounts`, vendored and run as Go. None of it is trailmap's, so the
 * comparison cannot agree with itself by construction.
 *
 *     TASKS_DATABASE=<tasks>/.git/tasks.db TASKS_CLI=<tasks> pnpm gate:lists
 */
