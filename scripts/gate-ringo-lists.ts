/** The RFC list's tabs are RFC statuses; ringo names its counters `cnt-<status>`. */
const RFC_TABS = ["active", "draft", "postponed", "closed", "superseded"] as const;
/** The backlog's tabs, ringo's `matchesFilter` values in `cnt-<filter>` order. */
const BACKLOG_TABS = ["open", "done", "ready", "draft", "blocked", "icebox"] as const;

/** What a row is compared as: an id, and the values the row states. */
interface Row {
  id: string;
}

/** One tab, as either side paints it. */
interface Painted<R extends Row> {
  /** The rows the tab lists, in the order it lists them. */
  rows: R[];
  /** Every tab's count, keyed by tab — the whole row is shown on every tab. */
  counts: Map<string, number>;
}

async function main(): Promise<number> {
  const fs = getFs();
  const path = getPath();
  const child = await getChildProcessAsync();

  // The snapshot is the reference implementation; prove it is the one
  // scripts/vendor-ringo.sh took before diffing anything against it.
  try {
    console.log(`ringo pin: ${await verifyRingoPin()}`);
  } catch (e) {
    console.error(`error: ${(e as Error).message}`);
    return 1;
  }

  const tasksDir = env.TASKS_CLI ?? path.join(Dir.pwd(), "tasks");
  if (!(await fs.exists(path.join(tasksDir, "bin", "tasks")))) {
    console.error(`error: no tasks CLI at ${tasksDir} — set TASKS_CLI to the checkout`);
    return 1;
  }

  // ONE SNAPSHOT, both sides, for the reason scripts/equivalence.ts gives at
  // length: this database is under continuous agent traffic, and two live
  // reads differ by timing alone.
  const snapshot = path.join(Dir.pwd(), "tmp", "ringo-lists-snapshot.sqlite3");
  await fs.mkdir!(path.dirname(snapshot), { recursive: true });
  for (const suffix of ["", "-wal", "-shm"]) {
    if (await fs.exists(snapshot + suffix)) await fs.unlink!(snapshot + suffix);
  }
  await Base.establishConnection(tasksDatabaseConfig());
  (await Base.leaseConnection()).execute(`VACUUM INTO '${snapshot.replace(/'/g, "''")}'`);
  (await Base.leaseConnection()).disconnectBang();
  await Base.establishConnection({ adapter: "sqlite3", database: snapshot, pool: 1 });
  await loadModelSchemas();
  ApplicationController.prependViewPath("app/views");

  const captured = path.join(Dir.pwd(), "tmp", "ringo-lists-cli.json");
  const cli = async (args: string[]): Promise<unknown> => {
    const result = child.spawnSync(path.join(tasksDir, "bin", "tasks"), [...args, "--json"], {
      cwd: tasksDir,
      encoding: "utf8",
      env: { ...env, TASKS_DB: snapshot },
      // Redirected to a file, not buffered: `list --json` is ~5MB of story
      // rows and spawnSync's 1MB default truncates it mid-object.
      out: captured,
    });
    if (result.status !== 0) throw new Error(`tasks ${args.join(" ")}: ${result.stderr.trim()}`);
    return JSON.parse(await fs.readFile!(captured, "utf8"));
  };

  const stories = (await cli(["list"])) as CliStory[];
  const ready = (await cli(["ready"])) as CliStory[];
  // Plain columns, read straight out of the snapshot rather than through
  // trailmap's models: the RFC list's rows are ringo's `idx.RFCs`, and nothing
  // about ports or ranking stands between a row and this SELECT.
  const rfcs = (
      await (await Base.leaseConnection()).selectAll(
      "SELECT id, title, status, owner, priority, superseded_by, packages, clusters FROM rfcs",
    )
  ).toArray() as unknown as CliRfc[];

  // `--self-test` proves the gate can still go red, by dropping ONE row from
  // trailmap's answer: a comparison that stopped comparing looks exactly like
  // a port that agrees. `--self-test=values` perturbs a row's VALUES instead,
  // leaving membership and order untouched — the acceptance criterion for
  // comparing them at all is that a change to the inherited-priority rule
  // turns this red, and dropping a row would not prove that.
  const selfTest = argv.some((a) => a === "--self-test" || a.startsWith("--self-test="));
  const valueTest = argv.includes("--self-test=values");

  // One perturbed page is enough to prove the comparison still bites, so the
  // backlog side is never dropped from — and the value perturbation is on the
  // backlog side, because the inherited flags live there.
  const problems = [
    ...compare(
      "/rfcs",
      RFC_TABS,
      await ringoRfcs(child, path, fs, rfcs, stories),
      await trailmapPages(RFC_TABS, RfcPagesController, "status", trailmapRfcRows, {
        dropOne: selfTest && !valueTest,
        disinherit: false,
      }),
    ),
    ...compare(
      "/backlog",
      BACKLOG_TABS,
      await ringoBacklog(fs, path, rfcs, stories, ready),
      await trailmapPages(BACKLOG_TABS, StoryPagesController, "filter", trailmapStoryRows, {
        dropOne: false,
        disinherit: valueTest,
      }),
    ),
  ];

  if (selfTest) {
    if (problems.length > 0) {
      const what = valueTest ? "un-inheriting one row's priority" : "dropping one row";
      console.log(`SELF-TEST OK: ${what} turned the gate red (${problems[0]})`);
      return 0;
    }
    console.error(
      valueTest
        ? "SELF-TEST FAILED: a row's inherited priority changed and the gate stayed green"
        : "SELF-TEST FAILED: a dropped row did not turn the gate red",
    );
    return 1;
  }
  if (problems.length === 0) {
    console.log(
      `\nEQUIVALENT: ${RFC_TABS.length + BACKLOG_TABS.length} tabs over ` +
        `${rfcs.length} rfcs and ${stories.length} stories.`,
    );
    return 0;
  }
  console.error(`\nNOT EQUIVALENT — ${problems.length} differences:`);
  for (const p of problems) console.error(`  ${p}`);
  return 1;
}

/** One story row of `tasks list --json` — the fields ringo's scripts read. */
interface CliStory {
  id: string;
  rfc: string;
  status: string;
  title: string | null;
  est_loc: number | null;
  cluster: string | null;
  priority: number | null;
  assignee: string | null;
  pr: number | null;
  packages: string[];
}

/** An RFC row, straight out of the snapshot's columns. */
interface CliRfc {
  id: string;
  title: string | null;
  status: string;
  owner: string | null;
  priority: number | null;
  superseded_by: string | null;
  /** JSON arrays, as the column stores them. */
  packages: string | null;
  clusters: string | null;
}

/** One of the RFC table's JSON-text list columns, as a list. */
function jsonList(column: string | null): string[] {
  if (!column) return [];
  const parsed: unknown = JSON.parse(column);
  return Array.isArray(parsed) ? (parsed as string[]) : [];
}

/** ringo's `/rfcs`, painted by ringo's own script over ringo's own counts. */
async function ringoRfcs(
  child: Awaited<ReturnType<typeof getChildProcessAsync>>,
  path: Awaited<ReturnType<typeof getPath>>,
  fs: Awaited<ReturnType<typeof getFs>>,
  rfcs: CliRfc[],
  stories: CliStory[],
): Promise<Map<string, Painted<RfcListRow>>> {
  // The done/total on each row, and the story_open the equal-priority tiebreak
  // sorts on, are ringo's `core.StoryCounts` (the rule behind its
  // `rfcStoryCounts`) — run as Go rather than described
  // again here, which is the whole point of vendoring it.
  const byRfc: Record<string, string[]> = {};
  for (const s of stories) (byRfc[s.rfc] ??= []).push(s.status);
  for (const r of rfcs) byRfc[r.id] ??= [];
  const counts = JSON.parse(
    await goHarness(child, path, fs, "counts", JSON.stringify(byRfc)),
  ) as Record<string, [number, number, number]>;

  const rows = rfcs.map((r) => ({
    ...r,
    clusters: jsonList(r.clusters),
    story_total: counts[r.id]![0],
    story_done: counts[r.id]![1],
    story_open: counts[r.id]![2],
  }));
  return runRingoScript(await fs.readFile!("vendor/ringo/rfcs-draw.js", "utf8"), { rfcs: rows },
    RFC_TABS, ringoRfcRows);
}

/** ringo's `/backlog`, painted by ringo's own script. */
async function ringoBacklog(
  fs: Awaited<ReturnType<typeof getFs>>,
  path: Awaited<ReturnType<typeof getPath>>,
  rfcs: CliRfc[],
  stories: CliStory[],
  ready: CliStory[],
): Promise<Map<string, Painted<StoryListRow>>> {
  const rfcStatus: Record<string, string> = {};
  const rfcPriorities: Record<string, number> = {};
  const rfcPackages: Record<string, string[]> = {};
  for (const r of rfcs) {
    rfcStatus[r.id] = r.status;
    if (r.priority !== null) rfcPriorities[r.id] = r.priority;
    // The parent side of the inherited-packages fallback. It was declared and
    // never filled, so ringo's rows carried no packages at all and every
    // inherited one on trailmap's side had nothing to be compared against —
    // invisible while only ids were compared.
    rfcPackages[r.id] = jsonList(r.packages);
  }
  // `allStories` (webhook/spawnloop.go:1373) hides stories under a CLOSED RFC:
  // the backlog only shows work under RFCs still in play.
  const all = stories.filter((s) => rfcStatus[s.rfc] !== "closed");
  return runRingoScript(await fs.readFile!("vendor/ringo/backlog-draw.js", "utf8"),
    { all, ready, rfc_status: rfcStatus, rfc_priorities: rfcPriorities, rfc_packages: rfcPackages },
    BACKLOG_TABS, ringoStoryRows);
}

/** Run ringo's vendored `cmd/core` over `input`, handing back its stdout. */
async function goHarness(
  child: Awaited<ReturnType<typeof getChildProcessAsync>>,
  path: Awaited<ReturnType<typeof getPath>>,
  fs: Awaited<ReturnType<typeof getFs>>,
  mode: string,
  input: string,
): Promise<string> {
  const out = path.join(Dir.pwd(), "tmp", `ringo-${mode}.json`);
  await fs.mkdir!(path.dirname(out), { recursive: true });
  const result = child.spawnSync("go", ["run", "./cmd/core", mode], {
    cwd: path.join(Dir.pwd(), "vendor", "ringo", "go"),
    encoding: "utf8",
    input,
    out,
  });
  if (result.status !== 0) throw new Error(`ringo's ${mode} exited ${result.status}: ${result.stderr.trim()}`);
  return await fs.readFile!(out, "utf8");
}

/**
 * Run one of ringo's page scripts over `payload`, once per tab, and read the
 * page back off the DOM stub.
 *
 * The stub is the smallest thing the scripts run against: elements that
 * remember what was assigned to them. They fetch their data on load and repaint
 * on a timer, so `fetch` hands back a promise that never settles and
 * `setInterval` does nothing — the data goes in through `render` instead,
 * which is the same function the real fetch resolves into.
 */
function runRingoScript<R extends Row>(
  source: string,
  payload: unknown,
  tabs: readonly string[],
  extract: (html: string) => R[],
): Map<string, Painted<R>> {
  const elements = new Map<string, StubElement>();
  const byId = (id: string): StubElement => {
    const existing = elements.get(id);
    if (existing) return existing;
    const made: StubElement = { textContent: "", innerHTML: "", style: {}, classList: { toggle: () => {} } };
    elements.set(id, made);
    return made;
  };
  const document = { getElementById: byId, querySelectorAll: () => [] };
  const api = new Function(
    "document", "location", "fetch", "setInterval", "window",
    `${source}\nreturn { render: render, setFilter: setFilter };`,
  )(document, { pathname: "/tasks" }, () => new Promise(() => {}), () => 0, {}) as {
    render: (data: unknown) => void;
    setFilter: (f: string) => void;
  };

  const painted = new Map<string, Painted<R>>();
  for (const tab of tabs) {
    api.setFilter(tab);
    api.render(payload);
    painted.set(tab, {
      rows: extract(elements.get("rows")?.innerHTML ?? ""),
      counts: new Map(
        tabs.map((t) => [t, Number.parseInt(String(elements.get(`cnt-${t}`)?.textContent ?? ""), 10)]),
      ),
    });
  }
  return painted;
}

/** What ringo's scripts need an element to be. */
interface StubElement {
  textContent: string;
  innerHTML: string;
  style: Record<string, string>;
  classList: { toggle: (name: string, on: boolean) => void };
}

/** trailmap's page, per tab, dispatched through the controller that serves it. */
async function trailmapPages<R extends Row>(
  tabs: readonly string[],
  controller: typeof ApplicationController,
  param: string,
  extract: (html: string) => R[],
  { dropOne, disinherit }: { dropOne: boolean; disinherit: boolean },
): Promise<Map<string, Painted<R>>> {
  const painted = new Map<string, Painted<R>>();
  for (const tab of tabs) {
    const tc = await controllerTestCase(controller);
    await tc.get("index", { params: { [param]: tab } });
    let body: string = tc.response.body;
    // A paged list is compared WHOLE: every page is fetched and its rows joined
    // in page order, so a row the paging dropped, repeated or reordered is a
    // difference from ringo's unpaged list like any other.
    const pages = Number.parseInt(/class="pager" data-pages="(\d+)"/.exec(body)?.[1] ?? "1", 10);
    const later: string[] = [];
    for (let page = 2; page <= pages; page++) {
      const next = await controllerTestCase(controller);
      await next.get("index", { params: { [param]: tab, page: String(page) } });
      later.push(next.response.body);
    }
    // `--self-test=values`: the page as it would read if the inherited-priority
    // rule had been ported wrong — the number kept, the `*` that says it came
    // from the parent RFC dropped. Membership and order are untouched, so only
    // the row-value comparison can catch it.
    if (disinherit) body = body.replace(/(<span class="tag prio"[^>]*>pri \d+)\*/, "$1");
    painted.set(tab, {
      rows: [body, ...later].flatMap((html) => extract(html)).slice(dropOne ? 1 : 0),
      // The tab row carries every tab's count on every tab, exactly as ringo's
      // does — `<a class="tab..." href="...?filter=ready">12 Ready</a>`.
      counts: new Map(
        [...body.matchAll(new RegExp(`class="tab[^"]*" href="[^"]*${param}=([a-z-]+)">(\\d+) `, "g"))]
          .map((m) => [m[1]!, Number.parseInt(m[2]!, 10)]),
      ),
    });
  }
  return painted;
}

/**
 * Every difference between the two paintings of one page.
 *
 * The tab COUNTS are compared once, on the first tab, and then each side is
 * asked whether its own count row is the same on every other tab. One wrong
 * count is one defect, and reporting it once per tab it appears on buried the
 * membership differences underneath it; the stability check is what keeps the
 * single comparison honest.
 */
function compare<R extends Row>(
  page: string,
  tabs: readonly string[],
  ringo: Map<string, Painted<R>>,
  trailmap: Map<string, Painted<R>>,
): string[] {
  const problems: string[] = [];
  const first = tabs[0]!;
  for (const counted of tabs) {
    const a = ringo.get(first)!.counts.get(counted);
    const b = trailmap.get(first)!.counts.get(counted);
    if (a !== b) problems.push(`${page}: the ${counted} tab counts ${a} in ringo, ${b} here`);
  }
  for (const [side, painted] of [["ringo", ringo], ["trailmap", trailmap]] as const) {
    const row = (tab: string) => tabs.map((t) => painted.get(tab)!.counts.get(t)).join("/");
    for (const tab of tabs.slice(1)) {
      if (row(tab) !== row(first)) {
        problems.push(`${page}?${tab}: ${side}'s tab counts differ from its own ${first} tab (${row(tab)} vs ${row(first)})`);
      }
    }
  }
  for (const tab of tabs) {
    const theirs = ringo.get(tab)!.rows;
    const ours = trailmap.get(tab)!.rows;
    const theirIds = theirs.map((r) => r.id);
    const ourIds = ours.map((r) => r.id);
    if (theirIds.join("\n") !== ourIds.join("\n")) {
      // Membership or order is wrong, so the rows are not the same rows and
      // diffing their values would report the misalignment once per row.
      problems.push(`${page}?${tab}: ${describe(theirIds, ourIds)}`);
      continue;
    }
    const rowProblems = compareValues(page, tab, theirs, ours);
    if (rowProblems.length === 0) {
      console.log(`ok  ${page}?${tab} (${theirs.length})`);
      continue;
    }
    problems.push(...rowProblems);
  }
  return problems;
}

/** How many differing rows to name before the report stops being useful. */
const ROW_REPORT_LIMIT = 5;

/**
 * What the rows of one tab SAY, row by row, once the two sides agree on which
 * rows they are and in what order.
 *
 * Reported per row rather than per field, and capped: one wrong rule — an
 * inherited priority read off the wrong RFC, say — is wrong on hundreds of
 * rows, and printing every one of them buries the next difference.
 */
function compareValues<R extends Row>(
  page: string,
  tab: string,
  ringo: R[],
  trailmap: R[],
): string[] {
  const problems: string[] = [];
  let differing = 0;
  for (const [i, theirs] of ringo.entries()) {
    const fields = diffFacts(theirs, trailmap[i]!);
    if (fields.length === 0) continue;
    differing++;
    if (problems.length < ROW_REPORT_LIMIT) {
      problems.push(`${page}?${tab}: ${theirs.id}: ${fields.join("; ")}`);
    }
  }
  if (differing > problems.length) {
    problems.push(`${page}?${tab}: ... and ${differing - problems.length} more rows differ`);
  }
  return problems;
}

/** The first differing position, which is the only useful thing to report. */
function describe(ringo: string[], trailmap: string[]): string {
  const at = ringo.findIndex((id, i) => id !== trailmap[i]);
  const first = at === -1 ? Math.min(ringo.length, trailmap.length) : at;
  // Sets, not `Array#includes`: a differing tab can hold thousands of ids on
  // both sides, and the quadratic scan turned a red gate into a slow one.
  const ringoHas = new Set(ringo);
  const trailmapHas = new Set(trailmap);
  const missing = ringo.filter((id) => !trailmapHas.has(id));
  const extra = trailmap.filter((id) => !ringoHas.has(id));
  return (
    `${ringo.length} in ringo vs ${trailmap.length} here; first difference at ${first} ` +
    `(ringo=${ringo[first] ?? "(end)"} trailmap=${trailmap[first] ?? "(end)"})` +
    (missing.length ? `; ${missing.length} missing here, e.g. ${missing[0]}` : "") +
    (extra.length ? `; ${extra.length} not in ringo, e.g. ${extra[0]}` : "")
  );
}

exit(await main());
