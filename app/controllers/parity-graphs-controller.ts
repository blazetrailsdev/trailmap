import { ApplicationController } from "./application-controller.js";
import { hasStatsDatabase } from "../../config/database.js";
import {
  PARITY_METRICS,
  gapsFor,
  lookupParityMetric,
  metricAvailable,
  metricColumns,
  type ParityMetric,
} from "../models/parity-metric.js";
import { serializeParitySeries, type ParitySeries } from "../serializers/parity-json.js";
import { ParityDay } from "../models/parity-day.js";
import { refreshProjectionIfStale } from "../models/parity-refresh.js";

/**
 * How many packages one request may chart.
 *
 * The page paints each package in one of eight fixed categorical slots of the
 * dataviz palette, so a ninth series would have to reuse a colour. ringo
 * refuses the request rather than reuse one, and so does this.
 */
const MAX_PACKAGES = 8;

/** A `?days=` window, as the lower bound the rollup wants. `all` means none. */
function sinceFor(days: string | undefined): string | undefined {
  if (!days || days === "all") return undefined;
  const n = Number(days);
  if (!Number.isInteger(n) || n <= 0) return undefined;
  return new Date(Date.now() - n * 86_400_000).toISOString().slice(0, 10);
}

/** The comma-separated list form the page's query parameters use. */
function splitCsv(value: string | undefined): string[] {
  return (value ?? "")
    .split(",")
    .map((part) => part.trim())
    .filter((part) => part.length > 0);
}

/**
 * `/graphs/parity` — how the trails port is converging, per package, over time.
 *
 * Ported from ringo's `/graphs/parity` (webhook/parity.go). The data layer is
 * trailmap's — five models on a third database (app/models/compare-run.ts) —
 * and the DRAWING is ringo's own, vendored rather than reimplemented
 * (vendor/ringo/parity.css, parity-draw.js, parity-body.html, regenerated by
 * scripts/vendor-ringo.sh). That split is deliberate and follows
 * scripts/gate-ringo-lists.ts' reasoning: a chart reimplemented from a reading
 * of chart.go would differ from ringo's in ways nobody could check, while a
 * vendored one differs only when ringo changes.
 *
 * The page is one HTML document with no data in it; `data` answers the JSON it
 * fetches. Two actions rather than content negotiation on one, because the
 * page and its data are not two representations of the same thing — the
 * document is static and the data is parameterised.
 */
export class ParityGraphsController extends ApplicationController {
  /**
   * The page. Static: every number on it arrives from `data`.
   *
   * It renders even with no stats database, because an unset `STATS_DB` is a
   * supported way to run trailmap (config/initializers/stats-database.ts) —
   * the page then says the source is missing instead of 500ing.
   */
  async show(): Promise<void> {
    await this.render({ locals: { statsConfigured: hasStatsDatabase() } });
  }

  /**
   * The JSON behind the page.
   *
   *   ?metrics=api,test     which comparison runs to chart, in picker order
   *   ?packages=a,b,c       up to MAX_PACKAGES
   *   ?days=30|90|365|all   merge-date window
   *
   * Every selected run is charted at once rather than one behind a picker,
   * because the question the page exists to answer — are the tests keeping up
   * with the API surface? — is a comparison between runs, and it is not a
   * comparison if you have to switch between them.
   *
   * The response shape is ringo's, field for field, so the vendored drawing
   * code needs no adaptation and scripts/gate-ringo-parity.ts can diff the two
   * endpoints directly.
   */
  async data(): Promise<void> {
    if (!hasStatsDatabase()) {
      await this.render({ json: { error: "STATS_DB is not set, so there are no stats to chart." } });
      return;
    }

    // `this.params` is a parameter map read with `.get()`, not a plain object
    // — reading it as one silently yields undefined for every parameter, which
    // looks exactly like a request that asked for nothing.
    const param = (name: string): string | undefined => {
      const value = this.params.get(name);
      return value === undefined || value === null ? undefined : String(value);
    };

    const selected: ParityMetric[] = [];
    for (const key of [...splitCsv(param("metrics")), ...splitCsv(param("metric"))]) {
      const metric = lookupParityMetric(key);
      if (!metric) {
        await this.render({ json: { error: `unknown metric ${key}` } });
        return;
      }
      if (!selected.some((already) => already.key === metric.key)) selected.push(metric);
    }
    if (selected.length === 0) selected.push(PARITY_METRICS[0]);

    const requested = splitCsv(param("packages"));
    if (requested.length > MAX_PACKAGES) {
      await this.render({ json: { error: `at most ${MAX_PACKAGES} packages at a time` } });
      return;
    }

    await refreshProjectionIfStale();

    // The picker only offers runs this database can actually chart, and only
    // charts the selected ones that survive that test — the stats schema is
    // the sync cron's, so trailmap can be older or newer than it.
    const available = PARITY_METRICS.filter((metric) => metricAvailable(metric));
    const gapsByMetric: Record<string, string[] | null> = {};
    const offered = available.map((metric) => {
      const gaps = gapsFor(metric);
      gapsByMetric[metric.key] = gaps;
      return { key: metric.key, label: metric.label, gaps };
    });
    const chartable = selected.filter((metric) => available.some((m) => m.key === metric.key));

    // The package list is the union over the selected runs, in canonical
    // order, because the page assigns a colour per package from it and a
    // package charted under one run must keep its colour under the others.
    // From the PROJECTION, not the comparison tables: this used to be a
    // `DISTINCT package` over 60k rows, per metric, per request.
    const perMetric = new Map<string, Set<string>>();
    const union = new Set<string>();
    for (const metric of chartable) {
      const names = new Set(
        (await ParityDay.where({ metric: metric.key }).distinct().pluck("package")).filter(
          (name): name is string => typeof name === "string" && name.length > 0,
        ),
      );
      perMetric.set(metric.key, names);
      for (const name of names) union.add(name);
    }
    const packages = [...union].sort();

    // A package no selected run measures is DROPPED rather than failing the
    // request: a bookmarked URL can name packages from another run, and the
    // two call tables hold only the synthetic `all`. The page says what it
    // ignored.
    const kept = requested.filter((pkg) =>
      chartable.some((metric) => perMetric.get(metric.key)?.has(pkg)),
    );
    const unknown = requested.filter((pkg) => !kept.includes(pkg));

    const since = sinceFor(param("days"));

    // One run at a time, deliberately. The page may have eight on the chart and
    // these are eight independent indexed reads, so Rails' `load_async` — fire
    // them all, then consume — is the obvious shape and was what this did.
    //
    // It is NOT USED because `loadAsync` is broken in the vendored trails:
    // only the FIRST call in the process returns rows and every later one
    // silently answers an empty set, whatever order they are consumed in.
    // Charting two runs lost the second, which is how it was found — the ringo
    // gate caught it. Reported upstream; the reads here are a few milliseconds
    // against a 14k-row table, so sequential costs nothing worth having.
    const series: ParitySeries[] = [];
    for (const metric of chartable) {
      const want = kept.filter((pkg) => perMetric.get(metric.key)?.has(pkg));
      if (want.length === 0) continue;
      const rows = await ParityDay.forChart(metric.key, want, since).toArray();
      series.push(...serializeParitySeries(rows, metric.key, want));
    }

    await this.render({
      json: {
        metrics_selected: selected.map((metric) => metric.key),
        gaps_by_metric: gapsByMetric,
        metrics: offered,
        packages,
        unknown_packages: unknown,
        max_packages: MAX_PACKAGES,
        series,
      },
    });
  }
}
